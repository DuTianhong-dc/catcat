/* ============================================================
 *  cat_vel_est.h — 机体线速度估计器(支撑腿运动学里程计)
 *
 *  干什么: 输出机体系线速度 → 观测 obs[0:3)。策略要靠它判"走得快不快"。
 *
 *  原理(2026-09-05 定稿, Python 原型 odometry_geo.py 验证通过):
 *    支撑腿足端在世界系静止 ⟹ 足端在机体系的位置变化率 = −机体速度(含转向牵连项)
 *      v = −(pdot_i + w × p_i)        支撑腿 i 的速度方程
 *    4 条腿各报一个 v_i → 取【分量中位数】做初值(天然抑制单腿异常)
 *                      → 按残差做高斯软权重加权平均(摆动腿残差大, 自动降权)
 *    ⚠️ 判据不需要全局定位: |pdot_i| 数学上恒等于足端【世界速度】模长(刚体速度合成)
 *
 *  输入: 12 个绝对关节角(rad, 与 MuJoCo qpos 同语义, 即观测 jpos 段 + 默认站姿)
 *        机体系角速度(rad/s) / 基座姿态四元数(w,x,y,z) —— 后者只用于抬高粗筛的重力对齐
 *  输出: 机体系线速度(m/s), 垂直分量恒为 0(单靠腿估不出)
 *
 *  ⚠️ 几何数据是按 **cat3.4** 定的(2026-09-26 确认): 后腿改用前小腿零件,
 *     后足偏移与前腿一致(腿长 194→181mm)。换腿型必须重核这三张表。
 *  验证: Python 原型仿真通过; FK 三独立参照物验证(初始态 <1mm / 站姿对比 1.21mm /
 *        机身高度闭环 0.44mm); 整体误差 0.073 m/s
 * ============================================================ */
#ifndef __CAT_VEL_EST_H
#define __CAT_VEL_EST_H
#include "stm32f4xx.h"
#include "cat_servo.h"      /* SERVO_COUNT */

/* 一开始就把站立基准建好(首拍输出 0)。上电时调一次。 */
void vel_est_init(void);

/* 每控制周期调一次。
 * jpos[12]     绝对关节角(rad), 顺序 = 观测序号(右后→左后→前右→前左, 每腿 abd/hip/knee)
 * gyro_rps[3]  机体系角速度(rad/s)
 * quat_wxyz[4] 基座姿态四元数(w,x,y,z)
 * dt_s         距上次调用的秒数(50Hz → 0.02); 传 0 或极小值会自动当 0.02 处理
 * v_out[3]     出参: 机体系线速度(m/s), v_out[2] 恒为 0 */
void vel_est_tick(const float jpos[SERVO_COUNT], const float gyro_rps[3],
                  const float quat_wxyz[4], float dt_s, float v_out[3]);

#endif
